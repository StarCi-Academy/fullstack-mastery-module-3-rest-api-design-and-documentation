package academy.starci.swagger;

public class CatRecord {
    private String name;
    private int age;

    public CatRecord() {}

    public CatRecord(String name, int age) {
        this.name = name;
        this.age = age;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public int getAge() {
        return age;
    }

    public void setAge(int age) {
        this.age = age;
    }
}
